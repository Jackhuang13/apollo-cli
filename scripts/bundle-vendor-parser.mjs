import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { execSync } from "node:child_process";

const __dirname = dirname(fileURLToPath(import.meta.url));
const tempDir = "/tmp/oxc-wasm-build";

console.log("Packing @oxc-parser/wasm@0.60.0...");
execSync(`mkdir -p ${tempDir} && npm pack @oxc-parser/wasm@0.60.0 --pack-destination ${tempDir}`, { stdio: "inherit" });
execSync(`tar -xzf ${tempDir}/oxc-parser-wasm-0.60.0.tgz -C ${tempDir}`, { stdio: "inherit" });

const jsPath = `${tempDir}/package/node/oxc_parser_wasm.js`;
const wasmPath = `${tempDir}/package/node/oxc_parser_wasm_bg.wasm`;

let js = readFileSync(jsPath, "utf8");
const wasm = readFileSync(wasmPath);
const b64 = wasm.toString("base64");

const replaceTarget = `const path = require('path').join(__dirname, 'oxc_parser_wasm_bg.wasm');
const bytes = require('fs').readFileSync(path);

const wasmModule = new WebAssembly.Module(bytes);
const wasmInstance = new WebAssembly.Instance(wasmModule, imports);
wasm = wasmInstance.exports;
module.exports.__wasm = wasm;`;

const replacement = `const bytes = Buffer.from("${b64}", "base64");
const wasmModule = new WebAssembly.Module(bytes);
const wasmInstance = new WebAssembly.Instance(wasmModule, imports);
wasm = wasmInstance.exports;
export const parseSync = module.exports.parseSync;
export default { parseSync };`;

js = `// Bundled @oxc-parser/wasm@0.60.0 with inlined WebAssembly
// Generated by scripts/bundle-vendor-parser.mjs - DO NOT EDIT MANUALLY
import { TextEncoder, TextDecoder } from "node:util";
import { Buffer } from "node:buffer";
const module = { exports: {} };
` + js
	.replace("const { TextEncoder, TextDecoder } = require(`util`);", "")
	.replace(replaceTarget, replacement);

const outPath = resolve(__dirname, "../apollo-cli-runtime/src/rlm/vendor/parser.js");
writeFileSync(outPath, js, "utf8");
console.log(`Successfully generated vendor bundle at: ${outPath} (${(js.length / 1024 / 1024).toFixed(2)} MB)`);
